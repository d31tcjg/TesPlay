export type MediaItem = {
  id: string;
  connectionId?: string;
  title: string;
  type: "movie" | "series" | "episode" | "live" | "folder" | "video" | "audio";
  source: string;
  poster?: string;
  backdrop?: string;
  description?: string;
  year?: string;
  duration?: number;
  category?: string;
  categoryLabel?: string;
  accessCategory?: string;
  playbackUrl?: string;
  externalUrl?: string;
  subtitle?: string;
  channelId?: string;
  publishedAt?: string;
  addedAt?: string;
  providerType?: string;
  contentKind?: string;
  sectionId?: string;
  artwork?: "poster" | "logo" | "thumbnail";
  watched?: boolean;
  unwatchedCount?: number;
  resumeSeconds?: number;
  unavailable?: boolean;
  unavailableReason?: string;
  seriesId?: string;
  seasonNumber?: number;
  episodeNumber?: number;
};
export type Profile = { id: string; name: string; color: string };
export type Auth = {
  scope?: "full" | "remote";
  deviceMode?: "browser" | "screen" | "remote";
  remoteRoomId?: string | null;
  setupRequired: boolean;
  user: { id: string; name: string; email: string | null; username: string; role: "owner" | "member"; canManageConnections?:boolean } | null;
  profiles: Profile[];
  activeProfileId: string | null;
};
export type Connection = {
  id: string;
  type: string;
  name: string;
  createdAt: string;
  configured: boolean;
  authMode?: "apiKey" | "oauth";
  oauthAuthorized?: boolean;
  summary?: string;
  shared?: boolean;
  access?: Grant;
  loadedCategories?: string[] | null;
};
export type Grant = { connectionId: string; kinds: string[]; sections: string[] | null; categories: string[] | null };
export type Starred = { connectionId: string; kind: "channel" | "category" | "section"; id: string; title: string };
export type Library = {
  plexWatchlist?: MediaItem[];
  plexNotes?: string[];
  stars?: Starred[];
  queue?: MediaItem[];
  favorites: MediaItem[];
  progress: {
    item: MediaItem;
    seconds: number;
    duration: number;
    updatedAt: string;
  }[];
};
export type Preferences = { autoPlayNext: boolean; hideYouTubeShorts?: boolean };
export type PlayerPreferences = { audioLanguage: string | null; subtitleLanguage: string | null; subtitlesEnabled: boolean; qualityId: 'auto' | '1080p' | '720p' | '480p' };
export type PlaybackSettings = { audioTrackId?: string; subtitleTrackId?: string; qualityId?: string; compatibility?: boolean; startOver?: boolean; sourceId?: string };
export type PlaybackChoice = { id: string; label: string; language?: string; codec?: string; selected?: boolean };
export type StreamChoice = { id: string; label: string; description?: string; addon: string; unavailable?: boolean; unavailableReason?: string };
export type PlaybackOptions = { item?: MediaItem; audio: PlaybackChoice[]; subtitles: PlaybackChoice[]; qualities: PlaybackChoice[]; sources?: StreamChoice[]; note?: string };
export type Playback = {
  defaults?: PlayerPreferences;
  provider?: "plex" | "youtube" | "stremio" | "channels";
  url: string;
  type: "hls" | "video" | "audio" | "external";
  streamKind?: "direct-file" | "continuous-ts" | "dual-input";
  audioUrl?: string;
  isLive?: boolean;
  message?: string;
  subtitles?: { id?: string; url: string; label: string; language?: string }[];
  audioTracks?: PlaybackChoice[];
  selectedAudioTrackId?: string;
  resumeSeconds?: number;
  settings?: PlaybackSettings;
};
export const itemKey = (item: MediaItem) =>
  `${item.connectionId || item.source}:${item.type}:${item.id}`;
